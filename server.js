import express from 'express';
import { init } from '@launchdarkly/node-server-sdk';
import { initAi } from '@launchdarkly/server-sdk-ai';
import Anthropic from '@anthropic-ai/sdk';

const port = process.env.PORT ?? 3000;

for (const name of ['LD_CLIENT_SIDE_ID', 'LD_SDK_KEY']) {
  if (!process.env[name]) {
    console.error(`${name} is missing. Copy .env.example to .env and fill it in (see README).`);
    process.exit(1);
  }
}

// The server-side SDK connects with the secret SDK key. The AI SDK sits on top of it.
const ldClient = init(process.env.LD_SDK_KEY);
try {
  await ldClient.waitForInitialization({ timeout: 10 });
} catch (err) {
  console.error(`Could not connect to LaunchDarkly: ${err.message} Check LD_SDK_KEY in .env.`);
  process.exit(1);
}
const aiClient = initAi(ldClient);

// With MODEL_API_KEY set, the chat calls Claude. Without it, the chat echoes what LaunchDarkly served.
const anthropic = process.env.MODEL_API_KEY ? new Anthropic({ apiKey: process.env.MODEL_API_KEY }) : null;

const app = express();
app.use(express.static('public'));

// The LaunchDarkly browser SDK ships as one self-contained ES module, so we
// serve it straight from node_modules and the page imports it. No bundler.
app.use('/sdk', express.static('node_modules/@launchdarkly/js-client-sdk/dist'));

// The browser SDK needs the environment's client-side ID. It is not a secret,
// but it lives in .env so that no key or ID is written into a tracked file.
app.get('/api/config', (req, res) => {
  res.json({ clientSideId: process.env.LD_CLIENT_SIDE_ID });
});

app.post('/api/chat', express.json(), async (req, res) => {
  const { message, context } = req.body;

  // 1. Ask LaunchDarkly which support-assistant variation this context gets: a model and a system prompt.
  //    The fallback, used if LaunchDarkly can't serve the config, switches the assistant off.
  const config = await aiClient.completionConfig('support-assistant', context, { enabled: false });
  if (!config.enabled) return res.json({ reply: 'The support assistant is switched off for this context.' });

  const model = config.model?.name ?? 'no model set';
  const system = config.messages?.find((m) => m.role === 'system')?.content ?? '';

  // 2. One tracker per run. trackMetricsOf times the call and records success or error plus token usage,
  //    which feed LaunchDarkly's autogenerated AI metrics.
  const tracker = config.createTracker();
  const result = await tracker.trackMetricsOf(
    (answer) => ({ success: true, tokens: answer.tokens }),
    () => (anthropic ? askClaude(model, system, message) : echo(model, system, message)),
  );
  res.json({ ...result, model, variation: tracker.getTrackData().variationKey });
});

// Call Claude with the model and system prompt that LaunchDarkly served
async function askClaude(model, system, message) {
  const response = await anthropic.messages.create({
    model,
    max_tokens: 4096,
    system,
    messages: [{ role: 'user', content: message }],
  });
  const text = response.content.filter((block) => block.type === 'text').map((block) => block.text).join('');
  const { input_tokens: input, output_tokens: output } = response.usage;
  return {
    reply: response.stop_reason === 'refusal' ? 'Claude declined to answer that.' : text,
    tokens: { input, output, total: input + output },
    estimated: false,
  };
}

// Echo mode: no model call. Token counts are ESTIMATES (about 4 characters per token), flagged as such.
async function echo(model, system, message) {
  const reply = `[Echo mode: no MODEL_API_KEY]\nModel: ${model}\nSystem prompt: ${system}\nYou asked: ${message}`;
  const input = Math.ceil((system.length + message.length) / 4);
  const output = Math.ceil(reply.length / 4);
  return { reply, tokens: { input, output, total: input + output }, estimated: true };
}

app.use((err, req, res, next) => res.status(500).json({ reply: `Something went wrong: ${err.message}` }));

app.listen(port, () => {
  console.log(`Feature flags demo running at http://localhost:${port}`);
  console.log(anthropic ? 'Chat: calling Claude (MODEL_API_KEY is set).' : 'Chat: echo mode (no MODEL_API_KEY).');
});
